def test_post_execution_not_achieved_generates_replacement_with_current_state_and_parent(
    app, recovery_case, monkeypatch
):
    monkeypatch.setattr(PlannerAgent, "build_and_validate_plans", _fake_generation)

    with app.app_context():
        original_id, _, current_snapshot_id = recovery_case
        planner = PlannerAgent(context=type("Ctx", (), {"db": db, "session": db.session, "run_id": 99})())

        result = planner.replan_after_execution(plan_id=original_id, required_candidate_count=2)

        assert result["status"] == "REPLAN_GENERATED"
        assert result["current_snapshot_id"] == current_snapshot_id
        assert len(result["plans"]) == 2

        children = Plan.query.filter_by(parent_plan_id=original_id).order_by(Plan.id).all()
        assert len(children) == 2
        assert all(child.snapshot_id == current_snapshot_id for child in children)
        assert all(child.status == "PROPOSED" for child in children)
        assert all(child.approval is None for child in children)
        assert all(child.execution is None for child in children)
        assert all("source_execution_id=" in (child.assumptions or "") for child in children)


def test_duplicate_replan_reuses_active_replacement_without_generating_again(
    app, recovery_case, monkeypatch
):
    calls = {"count": 0}

    def generation(*args, **kwargs):
        calls["count"] += 1
        return _fake_generation(*args, **kwargs)

    monkeypatch.setattr(PlannerAgent, "build_and_validate_plans", generation)

    with app.app_context():
        original_id, _, _ = recovery_case
        planner = PlannerAgent(context=type("Ctx", (), {"db": db, "session": db.session, "run_id": 100})())

        first = planner.replan_after_execution(plan_id=original_id, required_candidate_count=1)
        second = planner.replan_after_execution(plan_id=original_id, required_candidate_count=1)

        assert first["status"] == "REPLAN_GENERATED"
        assert second["status"] == "REPLAN_ALREADY_EXISTS"
        assert calls["count"] == 1
        assert len(Plan.query.filter_by(parent_plan_id=original_id).all()) == 1


