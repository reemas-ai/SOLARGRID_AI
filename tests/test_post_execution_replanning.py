def test_production_execution_uses_configured_budget_for_post_execution_replan(app, monkeypatch):
    """The execute API must not fall back to the generic 16-call interactive budget.

    The real recovery path can consume 21 deterministic tool calls in the worst case:
    Tool 12 + three Tool 16 topic lookups + Tool 13 + Tool 14 + Tool 02 (reserve refresh)
    + Tool 05 + twelve Tool 06-08 validations + Tool 09. The existing automation config
    deliberately provides 24 calls, so this test verifies that the API execution boundary
    actually uses that configured budget rather than silently constructing PlannerAgent()
    with its generic 16-call default.
    """
    captured = {}

    def fake_execute(self, *, plan_id, approval_id, current_snapshot_id):
        captured["max_tool_calls"] = self.limits.max_tool_calls
        captured["max_steps"] = self.limits.max_steps
        return {"status": "EXECUTION_ATTEMPTED", "execution": {"execution_id": 1}}

    monkeypatch.setattr(PlannerAgent, "execute_after_human_approval", fake_execute)

    # Use the real endpoint boundary, but replace the operation before any database
    # fixture is needed. The endpoint still constructs the production PlannerAgent.
    with app.app_context():
        from app import _run_with_trace
        result = _run_with_trace("PLAN_EXECUTION_BUDGET_REGRESSION", lambda planner: planner.execute_after_human_approval(
            plan_id=1, approval_id=1, current_snapshot_id=1
        ))

    assert result.status_code == 200
    assert captured["max_tool_calls"] == 24
    assert captured["max_steps"] == 32


def test_replan_budget_math_is_explicit_and_not_an_unbounded_increase():
    """Document the exact bounded recovery budget required by the current pipeline."""
    pre_replan = 1 + 3 + 1 + 1  # Tool 12 + Tool 16 topics + Tool 13 + Tool 14
    replan = 1 + (4 * 3) + 1 + 1  # Tool 02 if reserve refresh is needed + Tool 05 + 06-08 + Tool 09
    worst_case = pre_replan + replan

    assert worst_case == 21
    assert json.loads(open("config/automation_v1.json", encoding="utf-8").read())["planner_limits"]["max_tool_calls"] == 24
    assert 24 >= worst_case


def test_completed_tool14_recovery_automatically_invokes_existing_replan_operation(
    app, recovery_case, monkeypatch
):
    with app.app_context():
        original_id, _, _ = recovery_case
        planner = PlannerAgent(
            context=type("Ctx", (), {"db": db, "session": db.session, "run_id": 102})()
        )
        execution = Plan.query.get(original_id).execution
        calls = []

        def fake_call(name, payload):
            assert name == "assess_and_diagnose_outcome"
            return {
                "status": "SUCCESS",
                "data": {
                    "outcome_id": execution.outcome.id,
                    "goal_result": "NOT_ACHIEVED",
                    "replan_required": True,
                },
            }

        def fake_replan(*, plan_id, required_candidate_count=4, decision_policy_version="v1.0-demo"):
            calls.append((plan_id, required_candidate_count, decision_policy_version))
            return {
                "status": "REPLAN_GENERATED",
                "original_plan_id": plan_id,
                "current_snapshot_id": execution.outcome.id,
                "plans": [],
            }

        monkeypatch.setattr(planner, "_call", fake_call)
        monkeypatch.setattr(planner, "replan_after_execution", fake_replan)
        monkeypatch.setattr(
            "agents.planner_agent.SystemMemoryManager.evaluate_outcome_for_reusable_lesson",
            lambda self, outcome_id: {"status": "NOT_ELIGIBLE", "lesson_id": None},
        )

        result = planner.complete_post_execution_chain(execution_id=execution.id)

        assert result["status"] == "COMPLETED"
        assert result["replan"]["status"] == "REPLAN_GENERATED"
        assert calls == [(original_id, 4, "v1.0-demo")]


